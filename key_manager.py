"""
================================================================================
key_manager.py — Менеджер ключів SecureMsg
================================================================================

АРХІТЕКТУРА ЗБЕРІГАННЯ КЛЮЧІВ
-------------------------------

SecureMsg використовує файлову систему для зберігання криптографічних
матеріалів. Це просте, але надійне рішення для desktop-застосунку.

СТРУКТУРА ДИРЕКТОРІЙ:
----------------------
  ~/.securemsg/                    # Базова директорія (home directory)
    ├── keys/                      # Власні ключі користувача
    │   ├── my_private.pem         # Приватний ключ (захищений або відкритий)
    │   └── my_public.pem          # Публічний ключ (для передачі колегам)
    └── contacts/                  # Публічні ключі контактів
        ├── Ivan_Petrenko.pem      # Ключ колеги Івана
        ├── Client_ABC.pem         # Ключ клієнта
        └── ...

ЧОМУ ~/.securemsg/?
-------------------
• Стандартна практика для Unix-застосунків — зберігати дані у home dir
• Path.home() / ".securemsg" — кросплатформово:
  - Linux/macOS: /home/username/.securemsg
  - Windows: C:/Users/username/.securemsg
• Точка на початку — приховує директорію від ls (Unix convention)
• Легко знайти, легко резервувати, легко видаляти

БЕЗПЕКА ФАЙЛІВ:
---------------
• Приватний ключ: os.chmod(PRIVATE_KEY_PATH, 0o600)
  - 6 (owner): read + write
  - 0 (group): нічого
  - 0 (others): нічого
  - Це стандартна практика для SSH keys (~/.ssh/id_rsa має 0o600)
• Публічний ключ: не потребує захисту, можна передавати відкрито
• Контакти: публічні ключі, безпечно зберігати відкрито

ПАРОЛЬНИЙ ЗАХИСТ ПРИВАТНОГО КЛЮЧА:
-----------------------------------
• BestAvailableEncryption — використовує найсильніший алгоритм
  бібліотеки cryptography (зазвичай AES-256-CBC з PBKDF2-HMAC-SHA256)
• PBKDF2 (Password-Based Key Derivation Function 2):
  - Перетворює пароль користувача на криптографічний ключ
  - Використовує salt (випадкові дані) для унікальності
  - Багато ітерацій (зазвичай 100000+) для сповільнення brute-force
• Якщо пароль не встановлено — ключ зберігається у відкритому PEM
  (зручно, але ризиковано для корпоративного використання)

ВАЛІДАЦІЯ КЛЮЧІВ:
-----------------
• При збереженні контакту: load_public_key() перевіряє PEM-структуру
  та математичну цілісність ключової пари
• При завантаженні: cryptography сама перевіряє коректність
• Помилки перехоплюються та перетворюються на зрозумілі повідомлення
"""

import os
from pathlib import Path
from cryptography.hazmat.primitives.asymmetric.rsa import RSAPrivateKey, RSAPublicKey
from crypto_engine import (
    generate_key_pair, serialize_private_key, serialize_public_key,
    load_private_key, load_public_key,
)

# ============================================================================ #
#  КОНФІГУРАЦІЯ ШЛЯХІВ                                                        #
# ============================================================================ #

# Базова директорія — ~/.securemsg (кросплатформово через Path.home())
BASE_DIR = Path.home() / ".securemsg"

# Піддиректорія для власних ключів
KEYS_DIR = BASE_DIR / "keys"

# Піддиректорія для публічних ключів контактів
CONTACTS_DIR = BASE_DIR / "contacts"

# Шлях до приватного ключа поточного користувача
PRIVATE_KEY_PATH = KEYS_DIR / "my_private.pem"

# Шлях до публічного ключа поточного користувача
PUBLIC_KEY_PATH = KEYS_DIR / "my_public.pem"


# ============================================================================ #
#  УТИЛІТИ ДИРЕКТОРІЙ                                                          #
# ============================================================================ #

def ensure_dirs():
    """
    Створює необхідні директорії, якщо вони ще не існують.

    pathlib.Path.mkdir() з параметрами:
    • parents=True — створює всі проміжні директорії (mkdir -p)
    • exist_ok=True — не викликає помилку, якщо директорія вже існує

    Це ідемпотентна операція — безпечно викликати багато разів.
    """
    KEYS_DIR.mkdir(parents=True, exist_ok=True)
    CONTACTS_DIR.mkdir(parents=True, exist_ok=True)


# ============================================================================ #
#  УПРАВЛІННЯ ВЛАСНИМИ КЛЮЧАМИ                                                 #
# ============================================================================ #

def has_own_keys() -> bool:
    """
    Перевіряє, чи існують власні ключі користувача.

    Перевіряє ОБИДВА файли:
    • my_private.pem — приватний ключ (необхідний для дешифрування)
    • my_public.pem — публічний ключ (необхідний для ідентифікації)

    Якщо хоча б одного немає — ключова пара вважається відсутньою.

    ПОВЕРТАЄ:
    ----------
    bool: True якщо обидва файли існують, False інакше
    """
    return PRIVATE_KEY_PATH.exists() and PUBLIC_KEY_PATH.exists()


def create_own_keys(password: str | None = None) -> RSAPublicKey:
    """
    Генерує нову пару RSA-ключів і зберігає на диску.

    АЛГОРИТМ:
    ---------
    1. Створення директорій (якщо потрібно)
    2. Генерація пари RSA-2048 (generate_key_pair())
    3. Серіалізація приватного ключа (з паролем або без)
    4. Серіалізація публічного ключа
    5. Запис у файли
    6. Встановлення прав доступу 0o600 на приватний ключ

    ПАРАМЕТРИ:
    -----------
    password: str | None — пароль для шифрування приватного ключа.
        None = зберігати у відкритому вигляді (не рекомендовано
        для корпоративного використання).

    ПОВЕРТАЄ:
    ----------
    RSAPublicKey — публічний ключ (для відображення у інтерфейсі)

    ПРИМІТКА:
    ----------
    Якщо ключі вже існують — вони ПЕРЕЗАПИСУЮТЬСЯ.
    Це зручно для "перегенерації" ключів (з попередженням у UI).
    """
    ensure_dirs()

    # Генерація нової пари ключів
    private_key, public_key = generate_key_pair()

    # Перетворення пароля у bytes (якщо вказаний)
    pwd_bytes = password.encode() if password else None

    # Серіалізація та запис приватного ключа
    PRIVATE_KEY_PATH.write_bytes(
        serialize_private_key(private_key, pwd_bytes)
    )

    # Серіалізація та запис публічного ключа
    PUBLIC_KEY_PATH.write_bytes(
        serialize_public_key(public_key)
    )

    # Встановлення прав доступу: тільки власник (rw-------)
    # Це критично важливо для безпеки приватного ключа
    os.chmod(PRIVATE_KEY_PATH, 0o600)

    return public_key


def load_own_private_key(password: str | None = None) -> RSAPrivateKey:
    """
    Завантажує приватний ключ поточного користувача.

    АЛГОРИТМ:
    ---------
    1. Читання PEM-файлу
    2. Передача пароля у cryptography (якщо ключ зашифрований)
    3. Декодування та валідація ключової пари

    ПАРАМЕТРИ:
    -----------
    password: str | None — пароль для дешифрування PEM.
        None = ключ зберігається у відкритому вигляді.

    ПОВЕРТАЄ:
    ----------
    RSAPrivateKey — завантажений приватний ключ

    ВИКЛИКАЄ:
    ----------
    ValueError — якщо пароль неправильний, файл пошкоджений
                 або ключ не існує (FileNotFoundError прокидується)
    """
    pwd_bytes = password.encode() if password else None
    try:
        return load_private_key(PRIVATE_KEY_PATH.read_bytes(), pwd_bytes)
    except Exception:
        # Перетворюємо будь-яку помилку cryptography на зрозуміле повідомлення
        raise ValueError("Неправильний пароль або пошкоджений ключ.")


def load_own_public_key() -> RSAPublicKey:
    """
    Завантажує публічний ключ поточного користувача.

    Використовується рідко (зазвичай потрібен PEM-рядок для копіювання).
    Для криптографічних операцій використовується load_own_private_key().

    ПОВЕРТАЄ:
    ----------
    RSAPublicKey — завантажений публічний ключ
    """
    return load_public_key(PUBLIC_KEY_PATH.read_bytes())


def get_own_public_key_pem() -> str:
    """
    Повертає публічний ключ у PEM-форматі як текстовий рядок.

    Це основний метод для отримання ключа для:
    • Відображення у текстовому полі інтерфейсу
    • Копіювання у буфер обміну
    • Збереження у файл для передачі колезі

    ПОВЕРТАЄ:
    ----------
    str: PEM-кодований публічний ключ (з ASCII-маркерами)

    ВИКЛИКАЄ:
    ----------
    FileNotFoundError — якщо ключ ще не згенерований
    """
    return PUBLIC_KEY_PATH.read_text()


