def save_contact(name: str, public_key_pem: str):
    """
    Зберігає публічний ключ контакту у файл.

    АЛГОРИТМ:
    ---------
    1. Створення директорій (якщо потрібно)
    2. Запис PEM у файл contacts/{name}.pem

    ВАЛІДАЦІЯ:
    ----------
    Валідація PEM НЕ виконується тут — вона відбувається у
    AddContactDialog.validate_and_accept() перед викликом цієї функції.
    Це розділення відповідальності: UI валідує введення,
    а key_manager тільки зберігає.

    ПАРАМЕТРИ:
    -----------
    name: str — ім'я контакту (використовується як ім'я файлу)
    public_key_pem: str — PEM-кодований публічний ключ

    ПРИМІТКА:
    ----------
    Ім'я контакту стає ім'ям файлу. Спецсимволи у імені
    можуть спричинити проблеми на деяких файлових системах.
    У UI рекомендується фільтрувати імена (лише букви, цифри, _).
    """
    ensure_dirs()
    path = CONTACTS_DIR / f"{name}.pem"
    path.write_text(public_key_pem.strip())


def load_contact_key(name: str) -> RSAPublicKey:
    """
    Завантажує публічний ключ контакту як об'єкт RSAPublicKey.

    ВИКОРИСТАННЯ:
    -------------
    Ця функція використовується для криптографічних операцій
    (шифрування повідомлень для контакту).

    ПАРАМЕТРИ:
    -----------
    name: str — ім'я контакту (без розширення .pem)

    ПОВЕРТАЄ:
    ----------
    RSAPublicKey — публічний ключ контакту

    ВИКЛИКАЄ:
    ----------
    FileNotFoundError — якщо контакт не існує
    """
    path = CONTACTS_DIR / f"{name}.pem"
    if not path.exists():
        raise FileNotFoundError(f"Контакт «{name}» не знайдено.")
    return load_public_key(path.read_bytes())


def list_contacts() -> list[str]:
    """
    Повертає список імен усіх збережених контактів.

    АЛГОРИТМ:
    ---------
    1. Знаходить усі файли *.pem у директорії contacts/
    2. Для кожного файлу бере stem (ім'я без розширення)
    3. Сортує алфавітно

    ПОВЕРТАЄ:
    ----------
    list[str]: відсортований список імен контактів
    """
    ensure_dirs()
    return sorted(p.stem for p in CONTACTS_DIR.glob("*.pem"))


def get_contact_pem(name: str) -> str:
    """
    Повертає публічний ключ контакту у PEM-форматі як текст.

    ВИКОРИСТАННЯ:
    -------------
    • Відображення у текстовому полі інтерфейсу
    • Копіювання у буфер обміну
    • Збереження у файл

    ПАРАМЕТРИ:
    -----------
    name: str — ім'я контакту

    ПОВЕРТАЄ:
    ----------
    str: PEM-кодований публічний ключ

    ВИКЛИКАЄ:
    ----------
    FileNotFoundError — якщо контакт не існує
    """
    path = CONTACTS_DIR / f"{name}.pem"
    if not path.exists():
        raise FileNotFoundError(f"Контакт «{name}» не знайдено.")
    return path.read_text()


def delete_contact(name: str):
    """
    Видаляє контакт за ім'ям.

    БЕЗПЕЧНО: якщо файл не існує — жодної помилки не виникає
    (path.exists() перевіряє перед unlink).

    ПАРАМЕТРИ:
    -----------
    name: str — ім'я контакту для видалення
    """
    path = CONTACTS_DIR / f"{name}.pem"
    if path.exists():
        path.unlink()  # Видалення файлу


def import_contact_from_file(name: str, file_path: str):
    """
    Імпортує публічний ключ контакту з PEM-файлу.

    АЛГОРИТМ:
    ---------
    1. Читання PEM-файлу
    2. Валідація: перевірка, що це дійсно валідний публічний ключ
    3. Збереження через save_contact()

    ВАЛІДАЦІЯ:
    ----------
    load_public_key() перевіряє:
    • Коректність PEM-структури
    • Математичну цілісність ключової пари
    • Що це публічний ключ (не приватний)

    ПАРАМЕТРИ:
    -----------
    name: str — ім'я для нового контакту
    file_path: str — шлях до PEM-файлу з публічним ключем

    ВИКЛИКАЄ:
    ----------
    ValueError — якщо файл не містить валідний публічний ключ
    """
    pem_data = Path(file_path).read_text()
    # Перевірка що це справді валідний ключ
    load_public_key(pem_data.encode())
    save_contact(name, pem_data)
